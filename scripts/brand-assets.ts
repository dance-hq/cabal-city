// Regenerates every cabal.city logo file from lib/brand.ts and the bundled font:
//   pnpm brand
// Writes the wordmark outlines the site renders (components/brand/wordmark-paths.ts),
// the browser and home-screen icons in public/, downloadable logo files in
// public/brand/, and the desktop app + tray icons in desktop/build/.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { Resvg } from '@resvg/resvg-js'
import opentype from 'opentype.js'
import { BRAND, starPoints } from '../lib/brand'

const ROOT = path.resolve(import.meta.dirname, '..')
const out = (p: string) => path.join(ROOT, p)

// --- wordmark --------------------------------------------------------------------
// The font stays a build-time ingredient: the site ships outlines, not a third font.
const font = opentype.parse(readFileSync(out('assets/brand/PlusJakartaSans-ExtraBold.ttf')).buffer)
const SIZE = 100
const TRACKING = -0.025 // em, the board's tight set
const scale = SIZE / font.unitsPerEm

// The font's contextual alternates trip opentype.js's text shaper, and the
// wordmark has no ligatures, so place each glyph by hand with pair kerning.
function setLine(text: string, startX: number, baseline: number) {
  const path = new opentype.Path()
  let x = startX
  const glyphs = [...text].map((ch) => font.charToGlyph(ch))
  glyphs.forEach((g, i) => {
    path.extend(g.getPath(x, baseline, SIZE))
    const next = glyphs[i + 1]
    x += (g.advanceWidth ?? 0) * scale + TRACKING * SIZE
    if (next) x += font.getKerningValue(g, next) * scale
  })
  return { path, end: x }
}

const baseline = 100
const { path: cabal, end: cabalEnd } = setLine('cabal', 0, baseline)
// The board tucks the dot right up against the "l".
const { path: city } = setLine('.city', cabalEnd - 0.05 * SIZE, baseline)

type Box = { x1: number; y1: number; x2: number; y2: number }
const box = ([cabal.getBoundingBox(), city.getBoundingBox()] as Box[]).reduce((a, b) => ({
  x1: Math.min(a.x1, b.x1),
  y1: Math.min(a.y1, b.y1),
  x2: Math.max(a.x2, b.x2),
  y2: Math.max(a.y2, b.y2),
}))
const ascenderTop = cabal.getBoundingBox().y1 // top of the "b" and "l"

// Star sits to the left, centred on the letters above the baseline and a little
// taller than them, like the board's lockup.
const letters = baseline - ascenderTop
const starR = letters * 0.84
const starCy = ascenderTop + letters / 2
const gap = starR * 0.36
const starCx = box.x1 - gap - starR * 0.866 // the star's side tips are r·cos30 out

const minX = starCx - starR * 0.866
const minY = Math.min(box.y1, starCy - starR)
const maxY = Math.max(box.y2, starCy + starR)
const shift = (n: number) => +(n - minX).toFixed(1)
const width = +(box.x2 - minX).toFixed(1)
const height = +(maxY - minY).toFixed(1)

const translate = (p: opentype.Path) => {
  for (const c of p.commands) {
    for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2'] as const) {
      if (k in c) (c as unknown as Record<string, number>)[k] -= k.startsWith('x') ? minX : minY
    }
  }
  return p.toPathData(1)
}

const lockup = {
  width,
  height,
  star: starPoints(shift(starCx), +(starCy - minY).toFixed(1), +starR.toFixed(1)),
  cabal: translate(cabal),
  city: translate(city),
}

writeFileSync(
  out('components/brand/wordmark-paths.ts'),
  `// Generated by scripts/brand-assets.ts from Plus Jakarta Sans ExtraBold. Do not edit.\nexport const LOCKUP = ${JSON.stringify(lockup, null, 2)} as const\n`,
)

// --- svg builders ----------------------------------------------------------------
const star = (cx: number, cy: number, r: number, fill: string = BRAND.star) =>
  `<polygon points="${starPoints(cx, cy, r)}" fill="${fill}"/>`

const svg = (w: number, h: number, body: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">${body}</svg>`

// A rounded tile with the star, the app icon. `pad` leaves room around the tile
// (macOS expects its icons inset inside the 1024 canvas).
const tile = (size: number, { pad = 0, radius = 0.225, starScale = 0.31 } = {}) => {
  const inner = size - pad * 2
  return svg(
    size,
    size,
    `<rect x="${pad}" y="${pad}" width="${inner}" height="${inner}" rx="${inner * radius}" fill="${BRAND.ink}"/>` +
      star(size / 2, size / 2, inner * starScale),
  )
}

const lockupSvg = (cityFill: string, inkFill: string, bg?: string) => {
  const p = 24
  const w = width + p * 2
  const h = height + p * 2
  return svg(
    Math.round(w),
    Math.round(h),
    (bg ? `<rect width="100%" height="100%" fill="${bg}"/>` : '') +
      `<g transform="translate(${p} ${p})"><polygon points="${lockup.star}" fill="${BRAND.star}"/>` +
      `<path d="${lockup.cabal}" fill="${inkFill}"/><path d="${lockup.city}" fill="${cityFill}"/></g>`,
  )
}

const png = (file: string, source: string, w: number) => {
  const image = new Resvg(source, { fitTo: { mode: 'width', value: w } }).render().asPng()
  mkdirSync(path.dirname(out(file)), { recursive: true })
  writeFileSync(out(file), image)
}
const write = (file: string, text: string) => {
  mkdirSync(path.dirname(out(file)), { recursive: true })
  writeFileSync(out(file), text)
}

// --- browser + home screen -------------------------------------------------------
const favicon = tile(32, { radius: 0.25, starScale: 0.36 })
write('public/icon.svg', favicon)
png('public/icon-32.png', favicon, 32)
png('public/apple-icon.png', tile(180, { radius: 0, starScale: 0.3 }), 180) // iOS rounds it
png('public/cabal-icon.png', tile(256), 256)

// --- downloadable logo files -------------------------------------------------------
write('public/brand/cabal-city-on-dark.svg', lockupSvg(BRAND.cityOnInk, BRAND.paper, BRAND.ink))
write('public/brand/cabal-city-on-light.svg', lockupSvg(BRAND.cityOnPaper, BRAND.ink, BRAND.paper))
write('public/brand/cabal-city-transparent.svg', lockupSvg(BRAND.cityOnPaper, BRAND.ink))
write('public/brand/app-icon.svg', tile(512))
png('public/brand/app-icon.png', tile(512), 1024)
png(
  'public/brand/avatar.png',
  svg(400, 400, `<circle cx="200" cy="200" r="200" fill="${BRAND.ink}"/>${star(200, 200, 118)}`),
  400,
)

// --- desktop app -------------------------------------------------------------------
png('desktop/build/icon.png', tile(1024, { pad: 100, radius: 0.225, starScale: 0.31 }), 1024)
const trayStar = (fill: string) => svg(32, 32, star(16, 16, 15.5, fill))
png('desktop/build/tray.png', trayStar(BRAND.star), 16)
png('desktop/build/tray@2x.png', trayStar(BRAND.star), 32)
png('desktop/build/trayTemplate.png', trayStar('#000'), 16) // macOS tints template images
png('desktop/build/trayTemplate@2x.png', trayStar('#000'), 32)

console.log(`Lockup ${width}×${height}. Wrote wordmark paths, icons and logo files.`)
